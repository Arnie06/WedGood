  for select to authenticated using (app_private.can_manage_guests(wedding_id));

-- ---------------------------------------------------------------- helpers
create function app_private.is_uuid(p text) returns boolean
language sql immutable
set search_path = ''
as $$ select p ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' $$;

create function app_private.event_ok(j jsonb) returns boolean
language plpgsql immutable
set search_path = ''
as $$
declare
  k text;
  n text;
begin
  if j is null or jsonb_typeof(j) <> 'object' then return false; end if;
  foreach k in array array['name', 'kind', 'localDate'] loop
    if coalesce(jsonb_typeof(j -> k), 'null') not in ('null', 'string') then return false; end if;
  end loop;
  foreach k in array array['targetAttendance', 'capacity'] loop
    if coalesce(jsonb_typeof(j -> k), 'null') not in ('null', 'number') then return false; end if;
  end loop;
  if char_length(coalesce(app_private.jtext(j, 'name'), '')) not between 1 and 120 then return false; end if;
  if coalesce(app_private.jtext(j, 'kind'), 'other')
       not in ('ceremony', 'reception', 'rehearsal', 'welcome', 'brunch', 'other') then
    return false;
  end if;
  n := app_private.jtext(j, 'localDate');
  if n is not null and (n !~ '^\d{4}-\d{2}-\d{2}$' or to_char(n::date, 'YYYY-MM-DD') <> n) then
    return false;
  end if;
  if jsonb_typeof(j -> 'targetAttendance') = 'number'
     and ((j ->> 'targetAttendance') !~ '^\d{1,4}$' or (j ->> 'targetAttendance')::int > 5000) then
    return false;
  end if;
  if jsonb_typeof(j -> 'capacity') = 'number'
     and ((j ->> 'capacity') !~ '^\d{1,4}$' or (j ->> 'capacity')::int not between 1 and 5000) then
    return false;
  end if;
  return true;
exception when others then
  return false;
end;
$$;

-- Records a failed public lookup, or refuses when this client has failed too often.
create function app_private.rsvp_throttle(p_client text, p_record_failure boolean) returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_client is null or char_length(p_client) not between 1 and 64 then
    raise exception 'invalid client' using errcode = '22023';
  end if;
  if p_record_failure then
    insert into public.rsvp_failures (client_hash) values (p_client);
    delete from public.rsvp_failures where occurred_at < now() - interval '1 hour';
  elsif (select count(*) from public.rsvp_failures
          where client_hash = p_client and occurred_at > now() - interval '10 minutes') >= 20 then
    raise exception 'too many attempts' using errcode = 'RS429';
  end if;
end;
$$;
revoke all on function app_private.rsvp_throttle(text, boolean) from public, anon, authenticated;

-- Applies a validated status and meal to one member. Callers hold the invitation row lock.
create function app_private.apply_member_response(
  p_member uuid, p_status text, p_meal uuid, p_allow_pending boolean
) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_m public.invitation_members%rowtype;
  v_meal uuid := p_meal;
  v_active boolean;
begin
  select * into v_m from public.invitation_members where id = p_member for update;
  if not found or not v_m.active then
    raise exception 'unknown member' using errcode = '22023';
  end if;
  if p_status not in ('accepted', 'declined') and not (p_allow_pending and p_status = 'pending') then
    raise exception 'invalid status' using errcode = '22023';
  end if;
  -- Declining or resetting removes meal eligibility.
  if p_status <> 'accepted' then v_meal := null; end if;
  if v_meal is not null and v_meal is distinct from v_m.meal_option_id then
    select active into v_active from public.meal_options where id = v_meal and event_id = v_m.event_id;
    if v_active is distinct from true then
      raise exception 'invalid meal option' using errcode = '22023';
    end if;
  end if;
  if v_m.rsvp_status = p_status and v_m.meal_option_id is not distinct from v_meal then
    return false;
  end if;
  update public.invitation_members
    set rsvp_status = p_status, meal_option_id = v_meal,
        responded_at = case when p_status = 'pending' then null else now() end,
        version = version + 1
    where id = p_member;
  return true;
end;
$$;
revoke all on function app_private.apply_member_response(uuid, text, uuid, boolean)
  from public, anon, authenticated;

-- The narrow projection a guest sees: this invitation's members only, no contact details.
create function app_private.rsvp_projection(p_invitation uuid) returns jsonb
language sql stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'workspaceId', i.wedding_id,
    'weddingName', w.name,
    'label', i.label,
    'version', i.version,
    'deadline', i.deadline,
    'closed', (i.deadline is not null and now() > i.deadline),
    'plusOneRemaining', greatest(i.plus_one_quota - i.plus_ones_used, 0),
    'event', jsonb_build_object('name', e.name, 'kind', e.kind, 'localDate', e.local_date,
                                'timezone', w.timezone),
    'mealOptions', coalesce((select jsonb_agg(jsonb_build_object('id', m.id, 'name', m.name) order by m.created_at, m.id)
                               from public.meal_options m where m.event_id = e.id and m.active), '[]'::jsonb),
    'members', coalesce((select jsonb_agg(jsonb_build_object(
                  'id', im.id, 'name', g.full_name, 'isPlusOne', im.is_plus_one,
                  'status', im.rsvp_status, 'mealOptionId', im.meal_option_id)
                  order by im.is_plus_one, g.full_name, im.id)
                from public.invitation_members im
                join public.guests g on g.id = im.guest_id and g.wedding_id = im.wedding_id
                where im.invitation_id = i.id and im.active), '[]'::jsonb))
  from public.invitations i
  join public.events e on e.id = i.event_id and e.wedding_id = i.wedding_id
  join public.weddings w on w.id = i.wedding_id
  where i.id = p_invitation;
$$;
revoke all on function app_private.rsvp_projection(uuid) from public, anon, authenticated;

-- ---------------------------------------------------------------- owner RPCs
create function public.create_event(p_wedding uuid, p_event jsonb, p_idempotency_key text default null)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_wedding public.weddings%rowtype;
  v_prior uuid;
  v_id uuid;
begin
  v_wedding := app_private.lock_wedding_for_guests(p_wedding);
  if not app_private.event_ok(p_event) then
    raise exception 'invalid event' using errcode = '22023';
  end if;
  if p_idempotency_key is not null then
    v_prior := app_private.idem_claim(v_user, 'create_event:' || p_wedding::text, p_idempotency_key, md5(p_event::text));
    if v_prior is not null then return v_prior; end if;
  end if;
  if (select count(*) from public.events where wedding_id = p_wedding) >= 12 then
    raise exception 'too many events' using errcode = '54000';
  end if;
  insert into public.events (wedding_id, name, kind, local_date, target_attendance, capacity)
    values (p_wedding, app_private.jtext(p_event, 'name'), coalesce(app_private.jtext(p_event, 'kind'), 'other'),
            (app_private.jtext(p_event, 'localDate'))::date,
            (p_event ->> 'targetAttendance')::int, (p_event ->> 'capacity')::int)
    returning id into v_id;
  insert into public.audit_events (wedding_id, actor_id, entity_type, entity_id, action, safe_changes, revision)
    values (p_wedding, v_user, 'event', v_id, 'event.created', '{}'::jsonb, v_wedding.revision);
  if p_idempotency_key is not null then
    perform app_private.idem_done(v_user, 'create_event:' || p_wedding::text, p_idempotency_key, v_id);
  end if;
  return v_id;
end;
$$;

create function public.update_event(p_wedding uuid, p_event_id uuid, p_expected_version integer, p_event jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_wedding public.weddings%rowtype;
  v_old public.events%rowtype;
begin
  v_wedding := app_private.lock_wedding_for_guests(p_wedding);
  if not app_private.event_ok(p_event) then
    raise exception 'invalid event' using errcode = '22023';
  end if;
  select * into v_old from public.events where id = p_event_id and wedding_id = p_wedding for update;
  if not found then raise exception 'not permitted' using errcode = '42501'; end if;
  if v_old.version <> p_expected_version then
    raise exception 'version conflict' using errcode = '55000';
  end if;
  update public.events
    set name = app_private.jtext(p_event, 'name'), kind = coalesce(app_private.jtext(p_event, 'kind'), 'other'),
        local_date = (app_private.jtext(p_event, 'localDate'))::date,
        target_attendance = (p_event ->> 'targetAttendance')::int, capacity = (p_event ->> 'capacity')::int,
        version = version + 1
    where id = p_event_id;
  insert into public.audit_events (wedding_id, actor_id, entity_type, entity_id, action, safe_changes, revision)
    values (p_wedding, v_user, 'event', p_event_id, 'event.updated', '{}'::jsonb, v_wedding.revision);
end;
$$;

create function public.add_meal_option(p_wedding uuid, p_event_id uuid, p_name text) returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_wedding public.weddings%rowtype;
  v_name text := regexp_replace(btrim(coalesce(p_name, '')), '\s+', ' ', 'g');
  v_id uuid;
begin
  v_wedding := app_private.lock_wedding_for_guests(p_wedding);
  if char_length(v_name) not between 1 and 80 then
    raise exception 'invalid meal option' using errcode = '22023';
  end if;
  if not exists (select 1 from public.events where id = p_event_id and wedding_id = p_wedding) then
    raise exception 'not permitted' using errcode = '42501';
  end if;
  if (select count(*) from public.meal_options where event_id = p_event_id and active) >= 20 then
    raise exception 'too many meal options' using errcode = '54000';
  end if;
  insert into public.meal_options (wedding_id, event_id, name) values (p_wedding, p_event_id, v_name)
    returning id into v_id;
  insert into public.audit_events (wedding_id, actor_id, entity_type, entity_id, action, safe_changes, revision)
    values (p_wedding, v_user, 'meal_option', v_id, 'meal_option.created', '{}'::jsonb, v_wedding.revision);
  return v_id;
end;
$$;

-- Deactivating stops offering the option; guests who already chose it keep it and are still counted.
create function public.set_meal_option_active(p_wedding uuid, p_option_id uuid, p_expected_version integer, p_active boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_wedding public.weddings%rowtype;
  v_old public.meal_options%rowtype;
begin
  v_wedding := app_private.lock_wedding_for_guests(p_wedding);
  select * into v_old from public.meal_options where id = p_option_id and wedding_id = p_wedding for update;
  if not found then raise exception 'not permitted' using errcode = '42501'; end if;
  if v_old.version <> p_expected_version then
    raise exception 'version conflict' using errcode = '55000';
  end if;
  if p_active and not v_old.active
     and (select count(*) from public.meal_options where event_id = v_old.event_id and active) >= 20 then
    raise exception 'too many meal options' using errcode = '54000';
  end if;
  update public.meal_options set active = p_active, version = version + 1 where id = p_option_id;
  insert into public.audit_events (wedding_id, actor_id, entity_type, entity_id, action, safe_changes, revision)
    values (p_wedding, v_user, 'meal_option', p_option_id,
            case when p_active then 'meal_option.activated' else 'meal_option.deactivated' end,
            '{}'::jsonb, v_wedding.revision);
end;
$$;

-- p_groups: [{ "guestIds": [uuid, ...], "householdId": uuid | null }]. One invitation per group.
-- p_token_hashes: one SHA-256 hex digest per group, generated by the app. All or nothing; a guest
-- already invited to this event fails the whole call with 23505. A replayed key returns the same
-- invitations (their raw links are not recoverable; reissue to get a new link).
create function public.create_invitations(
  p_wedding uuid,
  p_event_id uuid,
  p_groups jsonb,
  p_plus_one_quota integer,
  p_expires_at timestamptz,
  p_token_hashes text[],
  p_idempotency_key text,
  p_deadline timestamptz default null
) returns table (o_invitation_id uuid, o_label text, o_replayed boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_wedding public.weddings%rowtype;
  v_prior uuid;
  v_batch uuid := gen_random_uuid();
  v_n integer;
  v_group jsonb;
  v_idx integer;
  v_ids uuid[];
  v_hid uuid;
  v_label text;
  v_inv uuid;
  v_gid text;
begin
  v_wedding := app_private.lock_wedding_for_guests(p_wedding);
  if p_idempotency_key is null or char_length(p_idempotency_key) not between 8 and 128
     or p_groups is null or jsonb_typeof(p_groups) <> 'array'
     or jsonb_array_length(p_groups) not between 1 and 200
     or p_plus_one_quota is null or p_plus_one_quota not between 0 and 5
     or p_expires_at is null or p_expires_at <= now() or p_expires_at > now() + interval '2 years'
     or (p_deadline is not null and (p_deadline <= now() or p_deadline > p_expires_at))
     or p_token_hashes is null
     or coalesce(cardinality(p_token_hashes), 0) <> jsonb_array_length(p_groups)
     or exists (select 1 from unnest(p_token_hashes) t where t is null or t !~ '^[0-9a-f]{64}$')
     or (select count(distinct t) from unnest(p_token_hashes) t) <> cardinality(p_token_hashes) then
    raise exception 'invalid invitations' using errcode = '22023';
  end if;
  if not exists (select 1 from public.events where id = p_event_id and wedding_id = p_wedding) then
    raise exception 'not permitted' using errcode = '42501';
  end if;
  v_prior := app_private.idem_claim(v_user, 'create_invitations:' || p_wedding::text, p_idempotency_key,
    md5(p_event_id::text || '|' || p_groups::text || '|' || p_plus_one_quota || '|' ||
        coalesce(p_deadline::text, '') || '|' || p_expires_at::text));
  if v_prior is not null then
    return query select i.id, i.label, true from public.invitations i
      where i.batch_id = v_prior and i.wedding_id = p_wedding order by i.created_at, i.id;
    return;
  end if;

  v_n := jsonb_array_length(p_groups);
  for v_idx in 1..v_n loop
    v_group := p_groups -> (v_idx - 1);
    if jsonb_typeof(v_group) <> 'object' or jsonb_typeof(v_group -> 'guestIds') <> 'array'
       or jsonb_array_length(v_group -> 'guestIds') not between 1 and 12
       or coalesce(jsonb_typeof(v_group -> 'householdId'), 'null') not in ('null', 'string') then
      raise exception 'invalid invitations' using errcode = '22023';
    end if;
    v_ids := '{}';
    for v_gid in select jsonb_array_elements_text(v_group -> 'guestIds') loop
      if not app_private.is_uuid(v_gid) then
        raise exception 'invalid invitations' using errcode = '22023';
      end if;
      v_ids := v_ids || v_gid::uuid;
    end loop;
    if (select count(distinct x) from unnest(v_ids) x) <> cardinality(v_ids)
       or (select count(*) from public.guests
            where id = any (v_ids) and wedding_id = p_wedding and archived_at is null) <> cardinality(v_ids) then
      raise exception 'invalid invitations' using errcode = '22023';
    end if;
    v_hid := null;
    v_label := null;
    if jsonb_typeof(v_group -> 'householdId') = 'string' then
      if not app_private.is_uuid(v_group ->> 'householdId') then
        raise exception 'invalid invitations' using errcode = '22023';
      end if;
      v_hid := (v_group ->> 'householdId')::uuid;
      select h.name into v_label from public.households h
        where h.id = v_hid and h.wedding_id = p_wedding and h.archived_at is null;
      if v_label is null then
        raise exception 'invalid invitations' using errcode = '22023';
      end if;
    end if;
    if v_label is null then
      select g.full_name into v_label from public.guests g
        where g.id = any (v_ids) order by g.full_name, g.id limit 1;
    end if;
    insert into public.invitations (wedding_id, event_id, household_id, batch_id, label, token_hash,
        plus_one_quota, deadline, expires_at, created_by)
      values (p_wedding, p_event_id, v_hid, v_batch, v_label, p_token_hashes[v_idx],
              p_plus_one_quota, p_deadline, p_expires_at, v_user)
      returning id into v_inv;
    insert into public.invitation_members (wedding_id, invitation_id, event_id, guest_id)
      select p_wedding, v_inv, p_event_id, x from unnest(v_ids) x;
  end loop;

  insert into public.audit_events (wedding_id, actor_id, entity_type, entity_id, action, safe_changes, revision)
    values (p_wedding, v_user, 'invitation_batch', v_batch, 'invitation.created',
            jsonb_build_object('invitations', v_n), v_wedding.revision);
  perform app_private.idem_done(v_user, 'create_invitations:' || p_wedding::text, p_idempotency_key, v_batch);
  return query select i.id, i.label, false from public.invitations i
    where i.batch_id = v_batch and i.wedding_id = p_wedding order by i.created_at, i.id;
end;
$$;

-- Replaces the link: the old token stops working at once.
create function public.reissue_invitation(p_wedding uuid, p_invitation_id uuid, p_expected_version integer, p_token_hash text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_wedding public.weddings%rowtype;
  v_inv public.invitations%rowtype;
begin
  v_wedding := app_private.lock_wedding_for_guests(p_wedding);
  if p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid token digest' using errcode = '22023';
  end if;
  select * into v_inv from public.invitations where id = p_invitation_id and wedding_id = p_wedding for update;
  if not found then raise exception 'not permitted' using errcode = '42501'; end if;
  if v_inv.version <> p_expected_version or v_inv.revoked_at is not null then
    raise exception 'version conflict' using errcode = '55000';
  end if;
  update public.invitations set token_hash = p_token_hash, version = version + 1 where id = p_invitation_id;
  insert into public.audit_events (wedding_id, actor_id, entity_type, entity_id, action, safe_changes, revision)
    values (p_wedding, v_user, 'invitation', p_invitation_id, 'invitation.reissued', '{}'::jsonb, v_wedding.revision);
end;
$$;

