-- R1-10 events, meal options, invitations and accountless RSVP (docs/07 "Invitations and guests",
-- docs/08 RSVP endpoints, docs/10 token rules).
--
-- Rules:
--  * Owner and partner manage events and invitations (same gate as guests). Clients have SELECT
--    only; every write is an RPC. token_hash is not selectable by any client role.
--  * An invitation is scoped to one event and (optionally) one household. Its members are existing
--    guests, plus quota-limited plus-ones created by the guest's own approved response. A guest has
--    at most one active membership per event (partial unique index), so responses are per event.
--  * Raw tokens are generated by the app and never stored or logged here; only SHA-256 hex digests.
--  * The public RSVP RPCs are executable by service_role only. The server calls them with the token
--    digest; they re-check expiry, revocation, deadline, version and quota under a row lock, return
--    a narrow projection (this invitation's members only) and never reveal why a token failed.
--  * Failed lookups are throttled per client hash (20 failures in 10 minutes -> RS429).
--  * Delivery is separate from response and not modelled here (R1-17); nothing is sent.

-- ---------------------------------------------------------------- tables
create table public.events (
  id uuid primary key default gen_random_uuid(),
  wedding_id uuid not null references public.weddings (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120 and name = btrim(name)),
  kind text not null default 'other'
    check (kind in ('ceremony', 'reception', 'rehearsal', 'welcome', 'brunch', 'other')),
  local_date date,
  target_attendance integer check (target_attendance is null or target_attendance between 0 and 5000),
  capacity integer check (capacity is null or capacity between 1 and 5000),
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (wedding_id, id)
);
create unique index events_name_uq on public.events (wedding_id, lower(name));
create trigger events_touch before update on public.events
  for each row execute function app_private.touch_updated_at();

create table public.meal_options (
  id uuid primary key default gen_random_uuid(),
  wedding_id uuid not null,
  event_id uuid not null,
  name text not null check (char_length(name) between 1 and 80 and name = btrim(name)),
  active boolean not null default true,
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (wedding_id, event_id, id),
  foreign key (wedding_id, event_id) references public.events (wedding_id, id) on delete cascade
);
create unique index meal_options_active_name_uq on public.meal_options (event_id, lower(name))
  where active;
create trigger meal_options_touch before update on public.meal_options
  for each row execute function app_private.touch_updated_at();

create table public.invitations (
  id uuid primary key default gen_random_uuid(),
  wedding_id uuid not null,
  event_id uuid not null,
  household_id uuid,
  batch_id uuid not null,
  label text not null check (char_length(label) between 1 and 120),
  token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  plus_one_quota integer not null default 0 check (plus_one_quota between 0 and 5),
  plus_ones_used integer not null default 0 check (plus_ones_used >= 0),
  deadline timestamptz,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  last_responded_at timestamptz,
  created_by uuid references auth.users (id) on delete set null,
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (wedding_id, id),
  unique (wedding_id, id, event_id),
  foreign key (wedding_id, event_id) references public.events (wedding_id, id) on delete cascade,
  foreign key (wedding_id, household_id) references public.households (wedding_id, id)
);
create index invitations_event_idx on public.invitations (wedding_id, event_id);
create index invitations_batch_idx on public.invitations (batch_id);
create trigger invitations_touch before update on public.invitations
  for each row execute function app_private.touch_updated_at();

create table public.invitation_members (
  id uuid primary key default gen_random_uuid(),
  wedding_id uuid not null,
  invitation_id uuid not null,
  event_id uuid not null,
  guest_id uuid not null,
  is_plus_one boolean not null default false,
  -- false once the invitation is revoked, which frees the guest for a new invitation to this event.
  active boolean not null default true,
  rsvp_status text not null default 'pending' check (rsvp_status in ('pending', 'accepted', 'declined')),
  meal_option_id uuid,
  responded_at timestamptz,
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (wedding_id, id),
  unique (invitation_id, guest_id),
  check (meal_option_id is null or rsvp_status = 'accepted'),
  foreign key (wedding_id, invitation_id, event_id)
    references public.invitations (wedding_id, id, event_id) on delete cascade,
  foreign key (wedding_id, guest_id) references public.guests (wedding_id, id),
  foreign key (wedding_id, event_id, meal_option_id)
    references public.meal_options (wedding_id, event_id, id)
);
-- One active response per event/person (docs/07).
create unique index invitation_members_active_uq on public.invitation_members (event_id, guest_id)
  where active;
create index invitation_members_event_idx on public.invitation_members (wedding_id, event_id);
create trigger invitation_members_touch before update on public.invitation_members
  for each row execute function app_private.touch_updated_at();

create table public.rsvp_failures (
  id bigint generated always as identity primary key,
  client_hash text not null check (char_length(client_hash) between 1 and 64),
  occurred_at timestamptz not null default now()
);
create index rsvp_failures_client_idx on public.rsvp_failures (client_hash, occurred_at);

alter table public.events enable row level security;
alter table public.meal_options enable row level security;
alter table public.invitations enable row level security;
